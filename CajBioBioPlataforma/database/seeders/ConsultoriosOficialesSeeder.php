    public function run(): void
    {
        $regiones = Region::whereIn('codigo', ['NB', 'BI', 'AR', 'LR', 'LL', 'AI'])
            ->get()->keyBy('codigo');

        $comunas = Comuna::all()->groupBy('region_id');

        foreach (self::UNIDADES as $u) {
            $region = $regiones->get($u['region_codigo']);
            if (! $region) {
                continue;
            }

            // Buscar la comuna dentro de la región
            $comunasRegion = $comunas->get($region->id) ?? collect();
            $comuna = $comunasRegion->first(function ($c) use ($u) {
                return mb_strtolower(trim($c->nombre)) === mb_strtolower(trim($u['comuna']));
            });

            if (! $comuna) {
                // Si no existe, crear la comuna en la región
                $comuna = Comuna::create([
                    'region_id' => $region->id,
                    'nombre' => $u['comuna'],
                ]);
                $comunasRegion->push($comuna);
                $comunas->put($region->id, $comunasRegion);
            }

            Consultorio::updateOrCreate(
                [
                    'nombre' => $u['nombre'],
                    'comuna_id' => $comuna->id,
                ],
                [
                    'region_id' => $region->id,
                    'tipo_unidad' => $u['tipo_unidad'],
                    'direccion' => $u['direccion'] ?: 'Sin dirección registrada',
                    'telefono' => $u['telefono'] ?: null,
                    'horario_atencion' => $u['horario_atencion'] ?: null,
                    'email' => $u['email'] ?: null,
                    'capacidad' => $u['capacidad'],
                    'activo' => true,
                    'acepta_postulaciones' => true,
                ]
            );
        }
    }
